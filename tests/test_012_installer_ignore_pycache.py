#!/usr/bin/env python3
"""RED tests for 012 — the installer never registers `__pycache__` as own artifact.

Contract: `docs/specs/012-installer-ignore-pycache/spec.md`
(approved by Pablo on 2026-11-01;
sha256 b475b7ddba130a25ecf9148568d1c893bc61791b3eac26d1f9c9c58d65002ca4).

Black-box: `install.sh` runs as a subprocess and only its published effects
are inspected (exit codes, stdout/stderr, the ownership manifest
`<CDAD_INSTALL_ROOT>/.cdad-install-manifest.json`). The installer
implementation is never read by these tests. Cache fixtures are planted in a
blind sandbox copy (whole-repo copytree, like
`tests/test_install_ownership.py::SandboxFixture`); skill directories are
discovered at runtime by the `SKILL.md` file name only — no implementation
content is inspected to derive the oracle.

Test -> postcondition mapping (one test per observable user promise; R2):

| Test | PC | Observable promise | Without this test, the user ... |
|---|---|---|---|
| test_pc1_manifest_never_registers_cache_shapes | PC-1 | An install over a source tree containing `__pycache__`/`.pyc`/`.pyo` registers none of them as owned artifacts. | ...would see phantom owned artifacts in the manifest, and a later cache cleanup would report their installs as "missing" without anything real changing. |
| test_pc2_install_with_cache_matches_install_without | PC-2 | Installing the same tree with cache produces the same registered artifact set as without it. | ...would get a manifest whose content depends on whether Python happened to have regenerated bytecode before the install — non-reproducible installs. |
| test_pc3_check_passes_with_regenerated_cache | PC-3 | `--check` over a valid install whose source tree regenerated `__pycache__` reports no drift/missing for that cause and exits 0. | ...would see `--check` FAIL right after running an installed skill script, with no real drift to resolve. |
| test_pc4_reinstall_prunes_preexisting_pyc_records | PC-4 | A reinstall prunes `.pyc` records already present in a previous manifest while content artifacts stay byte-identical. | ...would carry stale `.pyc` ownership records forever: every reinstall would re-adopt the junk instead of cleaning it. |

PC-5 (existing content behavior unchanged) is the regression surface named by
the spec acceptance criterion 2 (`test_install_ownership.py`,
`test_install_review5_regressions.py`, `test_009_001_installer_agent_overlay.py`,
`test_005_004_t2_installer_claims.py` stay green); it gets no new test here.

RED expected today (black-box probes on a scratch product copy, 2026-11-02):
- PC-1: install with 3 cache shapes planted in a skill dir registers 9 cache
  keys (3 shapes x 3 runtime destinations) in the ownership manifest.
- PC-2: the with-cache manifest has 12 extra keys vs the clean one.
- PC-3: `--check` after regenerating one `__pycache__/*.pyc` exits rc=1 with
  `DRIFT ... missing .../__pycache__/regen_mod.pyc` lines.
- PC-4: a reinstall over a manifest holding `.pyc` records keeps them
  (9 -> 12 keys as the regenerated file is re-registered too).
Every RED failure below is an `AssertionError` about that missing behavior,
never an `ImportError`/`SyntaxError`.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INSTALL_MANIFEST_NAME = ".cdad-install-manifest.json"

CACHE_FILE_NAMES = (
    "__pycache__/012_cache_probe.pyc",
    "012_loose.pyc",
    "012_loose.pyo",
)
CACHE_BYTES = b"# 012 cache fixture: bytecode must never be owned\n"


def run_installer(
    repo: Path, install_root: Path, *args: str
) -> subprocess.CompletedProcess[str]:
    """Run the installer of `repo` black-box against an isolated root."""
    env = os.environ.copy()
    env["CDAD_INSTALL_ROOT"] = str(install_root)
    env["CDAD_SKILL_EXTRA_DIRS"] = ""
    return subprocess.run(
        ["bash", str(repo / "install.sh"), *args],
        cwd=str(repo),
        env=env,
        text=True,
        capture_output=True,
        check=False,
    )


def load_install_manifest(install_root: Path) -> dict:
    path = install_root / INSTALL_MANIFEST_NAME
    assert path.is_file(), (
        "012 contract (PC-1): an install must publish the ownership manifest "
        f"{INSTALL_MANIFEST_NAME} at the install root; it is missing"
    )
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise AssertionError(
            f"012 contract: ownership manifest is not valid JSON: {exc}"
        ) from exc


def is_cache_artifact(rel: str) -> bool:
    """INV-1: exclusion is by route shape, not by concrete name."""
    return "__pycache__" in Path(rel).parts or rel.endswith((".pyc", ".pyo"))


def cache_keys(manifest: dict) -> list[str]:
    return sorted(
        key
        for key in (manifest.get("artifacts") or {})
        if is_cache_artifact(key)
    )


def cache_sources(manifest: dict) -> list[str]:
    found = []
    for key, record in (manifest.get("artifacts") or {}).items():
        source = str((record or {}).get("source", ""))
        if is_cache_artifact(source) or is_cache_artifact(key):
            found.append(f"{key} <- {source}")
    return sorted(found)


def skill_dirs(sandbox: Path) -> list[Path]:
    """Directories holding a skill, discovered by file name in the sandbox
    copy (blind fixture data — never the real tree, never file contents)."""
    found = set()
    for path in sorted((sandbox / "skills").rglob("SKILL.md")):
        if path.is_file():
            found.add(path.parent)
    assert found, (
        "012 fixture: the sandbox copy has no skills/*/SKILL.md to plant "
        "cache next to — the fixture cannot exercise the skill installer"
    )
    return sorted(found)


def plant_cache(sandbox: Path) -> list[str]:
    """Regenerate-like bytecode next to every skill of the sandbox copy."""
    planted = []
    for directory in skill_dirs(sandbox):
        for name in CACHE_FILE_NAMES:
            target = directory / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(CACHE_BYTES)
            planted.append(str(target.relative_to(sandbox)))
    return planted


class InstallerIgnorePycacheSandbox(unittest.TestCase):
    """Two blind product copies: pristine vs cache-planted. The copy ignores
    `.git` (probe 2026-11-02: a `.git`-less product copy installs rc=0 with
    the full skill set deployed; the installer is exercised from the sandbox
    cwd so every source enumeration hits the copy, never the real repo)."""

    @classmethod
    def setUpClass(cls) -> None:
        cls._tmp = tempfile.TemporaryDirectory(prefix="cdad-012-sandbox-")
        base = Path(cls._tmp.name)
        cls.pristine = base / "pristine"
        cls.cached = base / "cached"
        for dest in (cls.pristine, cls.cached):
            shutil.copytree(
                REPO_ROOT,
                dest,
                symlinks=True,
                ignore=shutil.ignore_patterns(
                    ".git", ".pytest_cache", "__pycache__"
                ),
            )
            if not (dest / "build" / "staging" / "manifest.json").is_file():
                from tests.product_staging import product_root

                shutil.copytree(
                    product_root() / "build" / "staging",
                    dest / "build" / "staging",
                )
        cls.planted = plant_cache(cls.cached)
        assert len(cls.planted) >= 3, (
            "012 fixture: cache planting produced no files; the RED setup "
            "would be vacuous"
        )

    @classmethod
    def tearDownClass(cls) -> None:
        cls._tmp.cleanup()

    def make_root(self) -> tuple[tempfile.TemporaryDirectory, Path]:
        tmp = tempfile.TemporaryDirectory(prefix="cdad-012-root-")
        self.addCleanup(tmp.cleanup)
        return tmp, Path(tmp.name)


class TestInstallerIgnorePycache(InstallerIgnorePycacheSandbox):
    def test_pc1_manifest_never_registers_cache_shapes(self) -> None:
        """PC-1: installing over a source tree with `__pycache__`, a loose
        `.pyc` and a loose `.pyo` registers none of them as owned artifacts.

        Without this test, the user would see phantom owned artifacts in the
        manifest, and cleaning the cache later would report "missing" without
        anything real changing.

        RED today: the manifest holds 9+ cache keys (each planted shape x
        each runtime destination)."""
        _, root = self.make_root()
        result = run_installer(self.cached, root, "--basic")
        self.assertEqual(result.returncode, 0, result.stderr or result.stdout)
        manifest = load_install_manifest(root)
        self.assertEqual(
            cache_keys(manifest),
            [],
            "PC-1: the ownership manifest must never include routes with a "
            f"`__pycache__` segment or `.pyc`/`.pyo` extension; found: "
            f"{cache_keys(manifest)[:10]}",
        )
        self.assertEqual(
            cache_sources(manifest),
            [],
            "PC-1: no manifest record may be sourced from a cache-shaped "
            f"route either; found: {cache_sources(manifest)[:10]}",
        )

    def test_pc2_install_with_cache_matches_install_without(self) -> None:
        """PC-2: the same tree with cache produces the same registered
        artifact set (keys and digests) as without it.

        Without this test, the user would get manifests whose content depends
        on whether Python happened to regenerate bytecode before the install.

        RED today: the with-cache manifest carries the extra cache keys."""
        _, clean_root = self.make_root()
        _, cache_root = self.make_root()
        clean = run_installer(self.pristine, clean_root, "--basic")
        self.assertEqual(clean.returncode, 0, clean.stderr or clean.stdout)
        cached = run_installer(self.cached, cache_root, "--basic")
        self.assertEqual(cached.returncode, 0, cached.stderr or cached.stdout)
        clean_manifest = load_install_manifest(clean_root)
        cache_manifest = load_install_manifest(cache_root)
        self.assertEqual(
            sorted(cache_manifest.get("artifacts", {})),
            sorted(clean_manifest.get("artifacts", {})),
            "PC-2: cache presence must not alter the registered artifact set "
            f"(extra keys: {sorted(set(cache_manifest.get('artifacts', {})) - set(clean_manifest.get('artifacts', {})))[:10]})",
        )
        self.assertEqual(
            cache_manifest.get("artifacts", {}),
            clean_manifest.get("artifacts", {}),
            "PC-2: shared artifacts must keep the same digests and sources "
            "whether cache is present or not",
        )

    def test_pc3_check_passes_with_regenerated_cache(self) -> None:
        """PC-3: `--check` over a valid install whose source tree regenerated
        `__pycache__` reports no drift/missing for that cause and exits 0.

        Without this test, the user would see `--check` FAIL right after
        running an installed skill script, with no real drift to resolve.

        RED today: `--check` exits rc=1 with
        `DRIFT ... missing .../__pycache__/<name>.pyc` lines."""
        _, root = self.make_root()
        first = run_installer(self.pristine, root, "--basic")
        self.assertEqual(first.returncode, 0, first.stderr or first.stdout)
        planted = plant_cache(self.pristine)
        try:
            check = run_installer(self.pristine, root, "--check")
            check_out = check.stdout + check.stderr
            self.assertEqual(
                check.returncode,
                0,
                "PC-3: --check must pass when the only change is regenerated "
                f"bytecode; output:\n{check_out}",
            )
            cache_lines = [
                line
                for line in check_out.splitlines()
                if re.search(r"(?i)(drift|missing)", line)
                and ("__pycache__" in line or ".pyc" in line or ".pyo" in line)
            ]
            self.assertEqual(
                cache_lines,
                [],
                "PC-3: --check must not report drift/missing for bytecode; "
                f"reported:\n" + "\n".join(cache_lines[:5]),
            )
        finally:
            for rel in planted:
                target = self.pristine / rel
                if target.is_file():
                    target.unlink()
            for parent in sorted(
                {str((self.pristine / rel).parent) for rel in planted},
                reverse=True,
            ):
                try:
                    Path(parent).rmdir()
                except OSError:
                    pass

    def test_pc4_reinstall_prunes_preexisting_pyc_records(self) -> None:
        """PC-4: a reinstall prunes `.pyc`/`.pyo` records already present in
        the previous manifest (both `artifacts` and `pending_removal`),
        leaving content artifacts byte-identical.

        Without this test, the user would carry stale `.pyc` ownership
        records forever: every reinstall would re-adopt the junk instead of
        cleaning it.

        Hand-edit (declared, the only one of this module): after a real
        first install, the manifest install #1 publishes is rewritten to
        also hold synthetic `.pyc` and `.pyo` records in both `artifacts`
        and `pending_removal` — the same simulation, expressed the way a
        previous install that registered bytecode would. Each record clones
        a real content entry (so its shape is valid) with only the key and
        `source` made cache-shaped. The reinstall must drop all four while
        content stays identical.

        RED today: the second install keeps (and grows) the cache records."""
        _, root = self.make_root()
        first = run_installer(self.cached, root, "--basic")
        self.assertEqual(first.returncode, 0, first.stderr or first.stdout)
        manifest_before = load_install_manifest(root)
        content_before = {
            key: record
            for key, record in (manifest_before.get("artifacts") or {}).items()
            if not is_cache_artifact(key)
        }
        self.assertTrue(
            content_before,
            "PC-4 precondition: the first install registered no content "
            "artifacts, so pruning cannot be shown to preserve anything",
        )
        template_key = sorted(content_before)[0]
        template_record = content_before[template_key]
        self.assertIsInstance(
            template_record,
            dict,
            "PC-4 precondition: manifest records must be provenance dicts "
            f"(got {type(template_record).__name__} for {template_key})",
        )
        template_source = str((template_record or {}).get("source", template_key))
        dest_dir = str(Path(template_key).parent)
        src_dir = str(Path(template_source).parent)
        seeded_keys = [
            str(Path(dest_dir) / "__pycache__" / "012_prune_probe.pyc"),
            str(Path(dest_dir) / "012_prune_probe.pyo"),
        ]
        seeded_sources = [
            str(Path(src_dir) / "__pycache__" / "012_prune_probe.pyc"),
            str(Path(src_dir) / "012_prune_probe.pyo"),
        ]
        for key in seeded_keys:
            self.assertTrue(
                is_cache_artifact(key),
                f"PC-4 precondition: seeded key {key} is not cache-shaped, "
                "so its survival would not prove anything about pruning",
            )
            self.assertNotIn(
                key,
                manifest_before.get("artifacts") or {},
                f"PC-4 precondition: seeded key {key} is already registered, "
                "so the seeding would not isolate preexisting records",
            )
        manifest_path = root / INSTALL_MANIFEST_NAME
        manifest = load_install_manifest(root)
        for section in ("artifacts", "pending_removal"):
            section_map = manifest.setdefault(section, {})
            self.assertIsInstance(
                section_map,
                dict,
                f"PC-4 precondition: manifest section {section} is not a map",
            )
            for key, source in zip(seeded_keys, seeded_sources):
                entry = dict(template_record)
                entry["source"] = source
                section_map[key] = entry
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        reseeded = load_install_manifest(root)
        for section in ("artifacts", "pending_removal"):
            for key in seeded_keys:
                self.assertIn(
                    key,
                    reseeded.get(section) or {},
                    f"PC-4 precondition: seeded record {key} missing from "
                    f"{section} before the reinstall — the pruning setup "
                    "would be vacuous",
                )
        second = run_installer(self.cached, root, "--basic")
        self.assertEqual(second.returncode, 0, second.stderr or second.stdout)
        manifest_after = load_install_manifest(root)
        leftovers = sorted(
            {
                key
                for section in ("artifacts", "pending_removal")
                for key in (manifest_after.get(section) or {})
                if is_cache_artifact(key)
            }
            | {
                f"{key} <- {(record or {}).get('source', '')}"
                for section in ("artifacts", "pending_removal")
                for key, record in ((manifest_after.get(section) or {}).items())
                if is_cache_artifact(str((record or {}).get("source", "")))
            }
        )
        self.assertEqual(
            leftovers,
            [],
            "PC-4: the reinstall must prune preexisting `.pyc`/`.pyo` records "
            "from `artifacts` and `pending_removal` even though the cache "
            "files are still in the source tree; still registered: "
            f"{leftovers[:10]}",
        )
        content_after = {
            key: record
            for key, record in (manifest_after.get("artifacts") or {}).items()
            if not is_cache_artifact(key)
        }
        self.assertEqual(
            content_after,
            content_before,
            "PC-4: pruning cache records must not touch content artifacts "
            "(same keys, digests and sources across the reinstall)",
        )


if __name__ == "__main__":
    unittest.main(verbosity=2)
